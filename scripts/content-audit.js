#!/usr/bin/env node
/* Content quality audit (Phase 1). Measures the question bank by role, gear, topic and review status, runs the rubric
   signals from js/quality.js, lists near-duplicate questions and builds a prioritised human-review queue.
   Output is deterministic, so docs/CONTENT_QUALITY.md is committed and `npm test` checks it is current.
   Usage: npm run content:audit            print the report
          npm run content:audit -- --write  regenerate docs/CONTENT_QUALITY.md
          npm run content:audit -- --json   machine-readable summary */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { dataFiles } = require('./lib/data-files');

function load(root) {
  const ctx = { setTimeout, clearTimeout, URL };
  ctx.window = ctx;
  vm.createContext(ctx);
  ['js/config.js', 'js/quality.js', 'js/engine.js', 'js/starter-paths.js'].concat(dataFiles(root))
    .forEach((f) => vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx, { filename: f }));
  return ctx.IGU;
}

function audit(root) {
  const IGU = load(root);
  const { bank, meta, quality: Q } = IGU;
  const statuses = Q.STATUSES;
  const onPath = {};
  (IGU.starterPaths || []).forEach((p) => (p.ids || []).forEach((id) => { onPath[id] = 1; }));

  const byStatus = {};
  statuses.forEach((s) => { byStatus[s] = 0; });
  bank.forEach((e) => { byStatus[Q.status(e)]++; });

  const grid = meta.roles.map((r) => ({
    role: r.id, name: r.name,
    cells: meta.levels.map((l) => {
      const items = bank.filter((e) => e.role === r.id && e.level === l.n);
      const c = { level: l.n, total: items.length };
      statuses.forEach((s) => { c[s] = items.filter((e) => Q.status(e) === s).length; });
      return c;
    })
  }));

  const flagCount = {};
  Object.keys(Q.FLAG_TEXT).forEach((k) => { flagCount[k] = 0; });
  bank.forEach((e) => Q.flags(e).forEach((f) => { flagCount[f]++; }));

  const signalByGear = meta.levels.map((l) => {
    const items = bank.filter((e) => e.level === l.n && Q.isReal(e));
    const pct = (k) => (items.length ? Math.round(100 * items.filter((e) => Q.signals(e)[k]).length / items.length) : 0);
    const words = items.map((e) => Q.signals(e).words).sort((a, b) => a - b);
    return { level: l.n, n: items.length, example: pct('example'), tradeoffs: pct('tradeoffs'), edgeCases: pct('edgeCases'), decision: pct('decision'),
      withRefs: items.filter((e) => Q.signals(e).references > 0).length, medianWords: words.length ? words[Math.floor(words.length / 2)] : 0 };
  });

  const topics = {};
  bank.forEach((e) => {
    const k = e.role + ' / ' + e.topic;
    topics[k] = topics[k] || { total: 0, real: 0, reviewed: 0 };
    topics[k].total++;
    if (Q.isReal(e)) topics[k].real++;
    if (Q.status(e) === 'reviewed') topics[k].reviewed++;
  });

  const dupes = Q.nearDuplicates(bank, 0.6).sort((a, b) => b.similarity - a.similarity || (a.a < b.a ? -1 : 1));
  const queue = bank.map((e) => ({ e, p: Q.reviewPriority(e, { onPath }) }))
    .filter((x) => x.p > 0)
    .sort((a, b) => b.p - a.p || a.e.level - b.e.level || a.e.id.localeCompare(b.e.id, 'en', { numeric: true }));

  return { IGU, bank, meta, Q, byStatus, grid, flagCount, signalByGear, topics, dupes, queue };
}

function markdown(a) {
  const { bank, meta, Q } = a;
  const out = [];
  const line = (s) => out.push(s === undefined ? '' : s);
  line('# Content quality report');
  line();
  line('Generated by `npm run content:audit -- --write` from the data files. Do not edit by hand; `npm test` fails when it is out of date.');
  line();
  line('The rubric signals are text heuristics. They point a reviewer at likely gaps (no example, no trade-offs, thin explanation and so on). They cannot judge technical correctness, so they never change a review status; only a person can mark an answer Human-reviewed or Needs correction. See CONTRIBUTING.md for the review workflow.');
  line();
  line('## Review status');
  line();
  line('| State | Meaning | Questions |');
  line('|---|---|---|');
  const meaning = {
    placeholder: 'No written answer yet; the app shows a practice structure instead',
    unreviewed: 'Written answer from early releases; who wrote it was not recorded',
    'ai-drafted': 'Written by an AI assistant, not yet checked by a person',
    reviewed: 'Checked by a person against the rubric, with a date',
    'needs-correction': 'A person found a problem that is not fixed yet; the app shows a warning'
  };
  Q.STATUSES.forEach((s) => line('| ' + Q.STATUS_NAMES[s] + ' | ' + meaning[s] + ' | ' + a.byStatus[s] + ' |'));
  line('| **Total** | | **' + bank.length + '** |');
  line();
  line('## Coverage by role and gear');
  line();
  line('Each cell: questions (AI-drafted / origin not recorded / human-reviewed / needs correction / pending).');
  line();
  line('| Role | ' + meta.levels.map((l) => 'Gear ' + l.n).join(' | ') + ' |');
  line('|---|' + meta.levels.map(() => '---').join('|') + '|');
  a.grid.forEach((r) => line('| ' + r.name + ' | ' + r.cells.map((c) => c.total + ' (' + [c['ai-drafted'], c.unreviewed, c.reviewed, c['needs-correction'], c.placeholder].join(' / ') + ')').join(' | ') + ' |'));
  line();
  line('## Rubric signals by gear (written answers only)');
  line();
  line('| Gear | Answers | Has an example | Has trade-offs | Has pitfalls or edge cases | Has decision-making language | With references | Median words |');
  line('|---|---|---|---|---|---|---|---|');
  a.signalByGear.forEach((g) => line('| ' + g.level + ' | ' + g.n + ' | ' + g.example + '% | ' + g.tradeoffs + '% | ' + g.edgeCases + '% | ' + g.decision + '% | ' + g.withRefs + ' | ' + g.medianWords + ' |'));
  line();
  line('## Rubric flags');
  line();
  line('| Flag | Questions |');
  line('|---|---|');
  Object.keys(a.flagCount).forEach((k) => line('| ' + Q.FLAG_TEXT[k] + ' | ' + a.flagCount[k] + ' |'));
  line();
  const keys = Object.keys(a.topics).sort();
  const single = keys.filter((k) => a.topics[k].total < 2);
  line('## Topic taxonomy');
  line();
  line(keys.length + ' role/topic pairs. ' + single.length + ' of them hold a single question, which makes topic filters and weak-topic detection less useful; merging them into broader topics is a reviewer task (topic is display data, so ids and progress are unaffected).');
  line();
  if (single.length) line('Single-question topics: ' + single.join(', ') + '.');
  line();
  line('## Near-duplicate questions');
  line();
  line('Question pairs whose wording overlaps by 60% or more (Jaccard similarity of words). A pair is not automatically a duplicate; a reviewer decides, and retires one with `IGU.retire(oldId, keptId)` so old links keep working.');
  line();
  if (!a.dupes.length) line('None found.');
  else { line('| Question | Question | Similarity |'); line('|---|---|---|'); a.dupes.forEach((d) => line('| ' + d.a + ' | ' + d.b + ' | ' + Math.round(100 * d.similarity) + '% |')); }
  line();
  line('## Human review queue (top 40)');
  line();
  line('Ordered by `quality.reviewPriority`: correction requests first, then answers whose origin was not recorded, rubric gaps, fundamentals (Gear 1 and 2) and questions on the starter learning paths. ' + a.queue.length + ' answers are waiting for a person in total.');
  line();
  line('| # | Question | Role | Gear | Status | Flags |');
  line('|---|---|---|---|---|---|');
  a.queue.slice(0, 40).forEach((x, i) => {
    const e = x.e;
    const q = e.q.replace(/\|/g, '\\|');
    line('| ' + (i + 1) + ' | ' + e.id + ': ' + (q.length > 90 ? q.slice(0, 89) + '…' : q) + ' | ' + e.role + ' | ' + e.level + ' | ' + Q.STATUS_NAMES[Q.status(e)] + ' | ' + Q.flags(e).filter((f) => f !== 'no-references').join(', ') + ' |');
  });
  line();
  return out.join('\n');
}

const REPORT = 'docs/CONTENT_QUALITY.md';

if (require.main === module) {
  const root = path.join(__dirname, '..');
  const a = audit(root);
  if (process.argv.includes('--json')) {
    process.stdout.write(JSON.stringify({ total: a.bank.length, byStatus: a.byStatus, flags: a.flagCount, signalsByGear: a.signalByGear, nearDuplicates: a.dupes,
      reviewQueue: a.queue.slice(0, 100).map((x) => ({ id: x.e.id, priority: x.p, flags: a.Q.flags(x.e) })) }, null, 2) + '\n');
  } else if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(root, REPORT), markdown(a));
    console.log('Wrote ' + REPORT);
  } else {
    console.log(markdown(a));
  }
}

module.exports = { audit, markdown, REPORT };
